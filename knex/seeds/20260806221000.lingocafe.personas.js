/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require("node:fs");
const path = require("node:path");

const SEED_FORMAT = "lingocafe-personas-seed-v1";
const PAYLOAD_PATH = path.join(__dirname, "data", "lingocafe.personas.json");

const readPayload = () => {
  const payload = JSON.parse(fs.readFileSync(PAYLOAD_PATH, "utf8"));
  if (payload.seed_format !== SEED_FORMAT) {
    throw new Error(`Unsupported persona seed format: ${payload.seed_format}`);
  }
  if (!/^[a-f0-9]{64}$/.test(payload.source_digest)) {
    throw new Error("Persona seed has an invalid source digest");
  }
  return payload;
};

/**
 * Load the complete books-owned persona corpus before conversation content.
 * The JSON payload is generated by books/.agents/skills/persona-push.
 *
 * @param { import("knex").Knex } knex
 * @returns { Promise<void> }
 */
exports.seed = async function seed(knex) {
  const payload = readPayload();

  await knex.transaction(async (trx) => {
    const columns = [
      "id",
      "persona_type",
      "status",
      "canonical_language",
      "working_label",
      "one_line",
      "stable_profile",
      "role_compatibility",
      "visual_fingerprint",
      "presentations",
      "is_visible",
      "source_schema_version",
      "source_path",
      "source_hash",
      "metadata",
    ];
    const rows = payload.personas.map((persona) =>
      Object.fromEntries(columns.map((column) => [column, persona[column]]))
    );
    await trx("lingocafe.personas")
      .insert(rows)
      .onConflict("id")
      .merge(columns.filter((column) => column !== "id"));

    const current = await trx("lingocafe.persona_publication_state")
      .select("source_digest")
      .where({ id: "current" })
      .first();
    if (!current) {
      await trx("lingocafe.persona_publication_state").insert({
        id: "current",
        source_digest: payload.source_digest,
      });
    } else if (current.source_digest !== payload.source_digest) {
      await trx("lingocafe.persona_publication_state")
        .where({ id: "current" })
        .update({
          source_digest: payload.source_digest,
          published_at: trx.fn.now(),
        });
    }
  });
};
