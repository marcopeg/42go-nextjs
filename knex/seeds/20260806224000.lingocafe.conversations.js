/* eslint-disable @typescript-eslint/no-require-imports */
const fs = require("node:fs");
const path = require("node:path");

const SEED_FORMAT = "lingocafe-conversations-seed-v1";
const PAYLOAD_PATH = path.join(
  __dirname,
  "data",
  "lingocafe.conversations.json"
);
const BATCH_SIZE = 250;

const TABLES = {
  conversation_categories: {
    columns: [
      "id",
      "status",
      "title",
      "description",
      "goal",
      "language_scope",
      "languages",
      "tags",
      "is_visible",
      "source_schema_version",
      "source_path",
      "source_hash",
      "metadata",
    ],
    conflict: ["id"],
  },
  conversation_scenarios: {
    columns: [
      "id",
      "status",
      "canonical_language",
      "title",
      "description",
      "learner_promise",
      "language_scope",
      "languages",
      "tags",
      "is_visible",
      "source_schema_version",
      "source_path",
      "source_hash",
      "metadata",
    ],
    conflict: ["id"],
  },
  conversation_variants: {
    columns: [
      "scenario_id",
      "id",
      "status",
      "canonical_language",
      "title",
      "description",
      "language_scope",
      "languages",
      "tags",
      "is_visible",
      "source_schema_version",
      "source_path",
      "source_hash",
      "metadata",
    ],
    conflict: ["scenario_id", "id"],
  },
  conversations: {
    columns: [
      "id",
      "scenario_id",
      "variant_id",
      "status",
      "language",
      "cefr_level",
      "title",
      "description",
      "tags",
      "is_visible",
      "source_schema_version",
      "source_path",
      "source_hash",
      "metadata",
    ],
    conflict: ["id"],
  },
  conversation_scenario_actors: {
    columns: [
      "scenario_id",
      "id",
      "position",
      "name",
      "role",
      "description",
      "metadata",
    ],
    conflict: ["scenario_id", "id"],
  },
};

const chunks = (rows) => {
  const result = [];
  for (let index = 0; index < rows.length; index += BATCH_SIZE) {
    result.push(rows.slice(index, index + BATCH_SIZE));
  }
  return result;
};

const pick = (row, columns) =>
  Object.fromEntries(columns.map((column) => [column, row[column]]));

const insertBatches = async (trx, table, rows) => {
  for (const batch of chunks(rows)) {
    await trx(`lingocafe.${table}`).insert(batch);
  }
};

const upsertBatches = async (trx, table, rows) => {
  const { columns, conflict } = TABLES[table];
  const mutable = columns.filter((column) => !conflict.includes(column));
  for (const batch of chunks(rows.map((row) => pick(row, columns)))) {
    await trx(`lingocafe.${table}`)
      .insert(batch)
      .onConflict(conflict)
      .merge(mutable);
  }
};

const replaceSingleScope = async (trx, table, column, ids, rows) => {
  await trx(`lingocafe.${table}`).whereIn(column, ids).del();
  await insertBatches(trx, table, rows);
};

const replaceVariantScope = async (trx, table, variants, rows) => {
  const keys = variants.map((variant) => [variant.scenario_id, variant.id]);
  await trx(`lingocafe.${table}`)
    .whereIn(["scenario_id", "variant_id"], keys)
    .del();
  await insertBatches(trx, table, rows);
};

const readPayload = () => {
  const payload = JSON.parse(fs.readFileSync(PAYLOAD_PATH, "utf8"));
  if (payload.seed_format !== SEED_FORMAT) {
    throw new Error(`Unsupported conversation seed format: ${payload.seed_format}`);
  }
  if (!/^[a-f0-9]{64}$/.test(payload.source_digest)) {
    throw new Error("Conversation seed has an invalid source digest");
  }
  return payload;
};

/**
 * Load the complete books-owned conversation corpus for development.
 *
 * The payload is generated by books/.agents/skills/conv-push. Knex owns the
 * transaction, so this seed intentionally has no advisory lock, catalog
 * preflight, or temporary SQL staging tables. Top-level source rows are
 * upserted by stable ID; child collections are replaced only inside their
 * explicitly exported parent scopes. Learner reads, stars, and progress are
 * never mutated.
 *
 * @param { import("knex").Knex } knex
 * @returns { Promise<void> }
 */
exports.seed = async function seed(knex) {
  const payload = readPayload();

  await knex.transaction(async (trx) => {
    const personaIds = [
      ...new Set(
        payload.variant_cast
          .map((row) => row.persona_id)
          .filter((personaId) => personaId !== null)
      ),
    ];
    const publishedPersonas = await trx("lingocafe.personas")
      .select("id")
      .whereIn("id", personaIds)
      .where({ status: "accepted", is_visible: true });
    if (publishedPersonas.length !== personaIds.length) {
      throw new Error(
        "Conversation seed requires the complete accepted persona seed first"
      );
    }

    await upsertBatches(
      trx,
      "conversation_categories",
      payload.categories
    );
    const categoryIds = payload.categories.map((row) => row.id);
    await replaceSingleScope(
      trx,
      "conversation_category_parents",
      "category_id",
      categoryIds,
      payload.parents
    );

    await upsertBatches(trx, "conversation_scenarios", payload.scenarios);
    const scenarioIds = payload.scenarios.map((row) => row.id);
    await replaceSingleScope(
      trx,
      "conversation_scenario_localizations",
      "scenario_id",
      scenarioIds,
      payload.scenario_localizations
    );
    await replaceSingleScope(
      trx,
      "conversation_category_scenarios",
      "category_id",
      categoryIds,
      payload.memberships
    );

    await upsertBatches(trx, "conversation_variants", payload.variants);
    await replaceVariantScope(
      trx,
      "conversation_variant_localizations",
      payload.variants,
      payload.variant_localizations
    );
    await upsertBatches(trx, "conversations", payload.conversations);

    const conversationIds = payload.conversations.map((row) => row.id);
    await replaceSingleScope(
      trx,
      "conversation_rounds",
      "conversation_id",
      conversationIds,
      []
    );
    await replaceVariantScope(
      trx,
      "conversation_variant_cast",
      payload.variants,
      []
    );

    await trx("lingocafe.conversation_scenario_actors")
      .whereIn("scenario_id", scenarioIds)
      .increment("position", 1000000);
    await upsertBatches(
      trx,
      "conversation_scenario_actors",
      payload.actors
    );

    const actorIdsByScenario = payload.actors.reduce((result, actor) => {
      const actors = result.get(actor.scenario_id) || [];
      actors.push(actor);
      result.set(actor.scenario_id, actors);
      return result;
    }, new Map());
    for (const scenarioId of scenarioIds) {
      const actorIds = (actorIdsByScenario.get(scenarioId) || []).map(
        (actor) => actor.id
      );
      const staleActors = trx("lingocafe.conversation_scenario_actors").where({
        scenario_id: scenarioId,
      });
      if (actorIds.length > 0) {
        staleActors.whereNotIn("id", actorIds);
      }
      await staleActors.del();
    }

    await insertBatches(
      trx,
      "conversation_variant_cast",
      payload.variant_cast
    );
    await insertBatches(trx, "conversation_rounds", payload.rounds);

    await replaceSingleScope(
      trx,
      "conversation_category_availability",
      "category_id",
      categoryIds,
      payload.availability
    );

    const current = await trx("lingocafe.conversation_publication_state")
      .select("source_digest")
      .where({ id: "current" })
      .first();
    if (!current) {
      await trx("lingocafe.conversation_publication_state").insert({
        id: "current",
        source_digest: payload.source_digest,
      });
    } else if (current.source_digest !== payload.source_digest) {
      await trx("lingocafe.conversation_publication_state")
        .where({ id: "current" })
        .update({
          source_digest: payload.source_digest,
          published_at: trx.fn.now(),
        });
    }
  });
};
